import fs from "node:fs";
import path from "node:path";

const projectRoot = path.resolve(import.meta.dirname, "..");
const sourceRoot = path.resolve(projectRoot, "../darkaid-source/src/rulesystems/dsa5aventurien");
const outputFile = path.resolve(projectRoot, "src/armory-data.ts");
const ruleSystem = JSON.parse(fs.readFileSync(path.join(sourceRoot, "rulesystem.json"), "utf8"));

const fileKinds = {
  "meleeweapons.json": "meleeweapon",
  "rangedweapons.json": "rangedweapon",
  "shields.json": "shield",
  "armor.json": "armor",
  "equipment.json": "equipment",
};

const categoryUrls = {
  meleeweapon: "https://dsa.ulisses-regelwiki.de/RS_Waffen.html",
  rangedweapon: "https://dsa.ulisses-regelwiki.de/RS_Waffen.html",
  shield: "https://dsa.ulisses-regelwiki.de/RS_Waffen.html",
  armor: "https://dsa.ulisses-regelwiki.de/RS_Ruestung.html",
  equipment: "https://dsa.ulisses-regelwiki.de/RK_Ausruestung.html",
};

const cleanText = (value) => String(value ?? "")
  .replace(/<br\s*\/?>/gi, " ")
  .replace(/<[^>]+>/g, " ")
  .replace(/\s+/g, " ")
  .trim();

const asPages = (value) => [...new Set((Array.isArray(value) ? value : [value])
  .map((entry) => cleanText(entry))
  .filter(Boolean))];

const hasRule = (value) => {
  const text = cleanText(value).toLocaleLowerCase("de");
  return Boolean(text && text !== "keine" && text !== "kein");
};

const entryScore = (entry) => {
  const relevant = [
    "name", "advantage", "disadvantage", "note", "complexity", "atmod", "pamod",
    "dp", "dpbonus", "enc", "pro", "inimod", "movmod", "weight", "kreutzers",
    "range", "reloadtime", "properties",
  ];
  return relevant.reduce((score, key) => score + (entry[key] == null ? 0 : 1), 0);
};

const candidates = new Map();
for (const rulebook of ruleSystem.rulebooks ?? []) {
  for (const relativeFile of rulebook.files ?? []) {
    const kind = fileKinds[path.basename(relativeFile)];
    if (!kind) continue;
    const absoluteFile = path.join(sourceRoot, relativeFile);
    if (!fs.existsSync(absoluteFile)) continue;
    const document = JSON.parse(fs.readFileSync(absoluteFile, "utf8"));
    for (const entry of document.data ?? []) {
      if (!entry?.id) continue;
      const catalogId = `${kind}:${entry.id}`;
      const values = candidates.get(catalogId) ?? [];
      values.push({
        entry,
        score: entryScore(entry),
        sourceId: rulebook.id,
        sourceLabel: rulebook.name,
        sourceShortLabel: rulebook.abbreviation ?? rulebook.name,
      });
      candidates.set(catalogId, values);
    }
  }
}

const complexityLabels = {
  primitive: "primitiv",
  simple: "einfach",
  complex: "komplex",
};

const result = {};
for (const [catalogId, values] of [...candidates.entries()].sort(([a], [b]) => a.localeCompare(b, "de"))) {
  const best = values.reduce((current, candidate) => candidate.score >= current.score ? candidate : current);
  const named = values.find((candidate) => cleanText(candidate.entry.name));
  const name = cleanText(best.entry.name) || cleanText(named?.entry.name) || catalogId.split(":").at(-1);
  const pages = asPages(best.entry.page);
  const properties = Array.isArray(best.entry.properties)
    ? [...new Set(best.entry.properties.map((entry) => cleanText(entry?.name)).filter(Boolean))]
    : [];
  const kind = catalogId.split(":", 1)[0];
  result[catalogId] = {
    sourceId: best.sourceId,
    sourceLabel: best.sourceLabel,
    sourceShortLabel: best.sourceShortLabel,
    pages,
    ...(best.entry.complexity ? { complexity: complexityLabels[best.entry.complexity] ?? cleanText(best.entry.complexity) } : {}),
    hasSpecialAdvantage: hasRule(best.entry.advantage),
    hasSpecialDisadvantage: hasRule(best.entry.disadvantage),
    hasAdditionalRules: properties.length > 0,
    propertyNames: properties,
    categoryUrl: categoryUrls[kind],
    regelwikiUrl: `https://dsa.ulisses-regelwiki.de/suche.html?keywords=${encodeURIComponent(name)}`,
  };
}

const source = `// Generated by scripts/generate-armory-data.mjs. Do not edit by hand.\n\n`
  + `export interface ArmoryItemInfo {\n`
  + `  sourceId: string;\n  sourceLabel: string;\n  sourceShortLabel: string;\n  pages: readonly string[];\n`
  + `  complexity?: string;\n  hasSpecialAdvantage: boolean;\n  hasSpecialDisadvantage: boolean;\n`
  + `  hasAdditionalRules: boolean;\n  propertyNames: readonly string[];\n  categoryUrl: string;\n  regelwikiUrl: string;\n`
  + `  armorType?: string;\n  armorZone?: string;\n  zoneProtection?: number;\n`
  + `  shortDescription?: string;\n  ruleNote?: string;\n  advantageText?: string;\n  disadvantageText?: string;\n`
  + `  derivedValues?: boolean;\n}\n\n`
  + `export const ARMORY_ITEM_INFO: Record<string, ArmoryItemInfo> = ${JSON.stringify(result, null, 2)};\n`;

fs.writeFileSync(outputFile, source);
console.log(`Wrote ${path.relative(projectRoot, outputFile)} (${Object.keys(result).length} Rüstkammer-Einträge).`);
